import AppKit
import Combine
import Defaults

struct ClipboardEntry: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let copiedAt: Date
}

/// Keeps a short, memory-only history of copied text for the clipboard area.
/// Nothing is written to disk, and entries marked concealed/transient by
/// password managers are never recorded.
@MainActor
final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()

    @Published private(set) var entries: [ClipboardEntry] = []

    private let entryLimit = 20
    private let maxLength = 2_000
    private let pollInterval: TimeInterval = 0.6
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var enabledCancellable: AnyCancellable?

    private init() {
        enabledCancellable = Defaults.publisher(.clipboardShelf)
            .sink { [weak self] change in
                Task { @MainActor in
                    if change.newValue {
                        self?.start()
                    } else {
                        self?.stop()
                    }
                }
            }
    }

    private func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll(force: true)
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
        entries.removeAll()
    }

    private func poll(force: Bool = false) {
        let pasteboard = NSPasteboard.general
        guard force || pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if let types = pasteboard.types, !ignoredTypes.isDisjoint(with: types) { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        record(String(text.prefix(maxLength)))
    }

    private func record(_ text: String) {
        entries.removeAll { $0.text == text }
        entries.insert(ClipboardEntry(text: text, copiedAt: Date()), at: 0)
        if entries.count > entryLimit {
            entries.removeLast(entries.count - entryLimit)
        }
    }

    func copy(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        // Our own write: don't treat it as a new copy, just bring it forward.
        lastChangeCount = pasteboard.changeCount
        record(entry.text)
    }

    func remove(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }
    }

    func clear() {
        entries.removeAll()
    }
}
